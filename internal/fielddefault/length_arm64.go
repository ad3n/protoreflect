func escapedBytesLenLarge(data []byte) int {
	length := 0
	for len(data) >= 65536 {
		length += escapedBytesLenNEON(data[:65536])
		data = data[65536:]
	}

	n := len(data) &^ 15
	return length + escapedBytesLenNEON(data[:n]) + escapedBytesLen(data[n:])
}

func escapedBytesLenShort(data []byte) int {
	length := len(data)
	for _, c := range data {
		length += int(escapedByteExtra[c])
	}

	return length
}
